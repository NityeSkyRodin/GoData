// ---------- Shared card templates ----------
 
function twoDigits(number) {
    return String(number).padStart(2, '0');
}
 
// Track outline as an SVG string (empty when the track isn't in TRACK_SVGS)
function trackSvg(trackName, { strokeWidth = 8, extraAttrs = '', className = 'w-full h-full' } = {}) {
    const path = getTrackSvgPath(trackName);
    if (!path) return '';
    return `
        <svg viewBox="0 0 500 400" ${extraAttrs} class="${className}">
            <path d="${path}" fill="none" stroke="currentColor" stroke-width="${strokeWidth}" stroke-linejoin="round" stroke-linecap="round"></path>
        </svg>
    `;
}
 
function statCard(label, value, { sub = '', accent = false, index = 0 } = {}) {
    // Numbers get a big font, names a smaller uppercase one so they still fit
    const isNumber = typeof value === 'number' || /^P?[\d./+-]+$/.test(String(value));
    const valueClass = isNumber ? 'text-4xl' : 'text-xl uppercase tracking-wide truncate';
    return `
        <div class="relative overflow-hidden bg-[#10141C] border border-[#232734] corner-cut p-5 min-h-[104px]">
            <div class="text-[10px] font-bold uppercase tracking-[0.2em] text-slate-500">${label}</div>
            <div class="font-header font-black mt-2 ${valueClass} ${accent ? 'text-[#0090D0]' : 'text-white'}">${value}</div>
            ${sub ? `<div class="text-[10px] font-bold uppercase tracking-[0.15em] text-[#0090D0] mt-1 truncate">${sub}</div>` : ''}
            <div class="watermark">${twoDigits(index + 1)}</div>
        </div>
    `;
}
 
// Small square badge for one result: '-' when absent, X for a DNF, blue for podiums
function positionBadge(result, size = 'w-6 h-6') {
    const base = `${size} inline-flex items-center justify-center corner-cut`;
    if (!result) {
        return `<span class="${base} bg-[#151821] text-slate-600 border border-[#232734]">-</span>`;
    }
    const pos = result.position;
    if (!isFinished(result)) {
        return `<span class="${base} bg-red-500/10 text-red-400 border border-red-500/20">X</span>`;
    } else if (pos === 1) {
        return `<span class="${base} bg-[#0090D0] text-white font-black">1</span>`;
    } else if (pos <= 3) {
        return `<span class="${base} bg-[#0090D0]/30 text-white border border-[#0090D0]/50 font-bold">${pos}</span>`;
    } else if (pos <= 10) {
        return `<span class="${base} bg-[#232734] text-white border border-[#232734]">${pos}</span>`;
    }
    return `<span class="${base} bg-[#151821] text-slate-400 border border-[#232734]">${pos}</span>`;
}

// Build form guide (last 5 feature races)
function formGuide(races, driverName) {
    const formHTML = races.slice(-5)
        .map(race => positionBadge(findResult(race, 'race', driverName)))
        .join('');

    return `<div class="flex items-center gap-1 font-header text-[11px]">${formHTML}</div>`;
}

// Same look as positionBadge, but for the points a team scored in one weekend
function pointsBadge(points, trackName) {
    const base = 'w-7 h-6 inline-flex items-center justify-center corner-cut';
    const title = `title="${trackName}: ${points} pts"`;
    if (points >= 30) {
        return `<span ${title} class="${base} bg-[#0090D0] text-white font-black">${points}</span>`;
    } else if (points >= 15) {
        return `<span ${title} class="${base} bg-[#0090D0]/30 text-white border border-[#0090D0]/50 font-bold">${points}</span>`;
    } else if (points > 0) {
        return `<span ${title} class="${base} bg-[#232734] text-white border border-[#232734]">${points}</span>`;
    }
    return `<span ${title} class="${base} bg-[#151821] text-slate-600 border border-[#232734]">0</span>`;
}

function teamFormGuide(races, team) {
    const recent = races.slice(-5);
    const points = team.weekendPoints.slice(-5);
    return `<div class="flex items-center gap-1 font-header text-[11px]">${points.map((p, i) => pointsBadge(p, recent[i].track_name)).join('')}</div>`;
}

// ---------- Result helpers ----------

function findResult(race, session, driverName) {
    return (race.data[session] || []).find(r => r.driver_name === driverName);
}

function weekendPoints(race, driverName) {
    return ['qualifying', 'sprint', 'race'].reduce((sum, session) =>
        sum + (findResult(race, session, driverName)?.points || 0), 0);
}

function isFinished(result) {
    return String(result?.status).toLowerCase() === 'finished';
}

function getFastestLap(results) {
    return results
        .filter(driver => parseLapTime(driver.best_lap_time) !== null)
        .sort((a, b) => parseLapTime(a.best_lap_time) - parseLapTime(b.best_lap_time))[0];
}
 
