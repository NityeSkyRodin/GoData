// The tyres a driver used in order, with the number of laps on each set below the icon
function tyreStrategy(stints, { size = 26, showLaps = true } = {}) {
    if (!stints.length) return '<span class="text-slate-600">-</span>';

    let firstLap = 1;
    const parts = stints.map((stint, i) => {
        const laps = stint.end_lap - firstLap + 1;
        const title = `${stint.compound} · lap ${firstLap}–${stint.end_lap}`;
        firstLap = stint.end_lap + 1;
        return `
            ${i > 0 ? '<span class="text-slate-600 text-sm font-bold">›</span>' : ''}
            <span class="flex flex-col items-center" title="${title}">
                ${tyreIcon(stint.compound, size)}
                ${showLaps ? `<span class="text-[10px] font-bold text-slate-500 mt-0.5">${laps}L</span>` : ''}
            </span>
        `;
    });
    return `<div class="flex items-center gap-1.5">${parts.join('')}</div>`;
}

function parseLapTime(time) {
    // "1:37.562" -> 97.562 seconds, null when there is no valid time
    const match = /^(?:(\d+):)?(\d+(?:\.\d+)?)$/.exec(String(time ?? '').trim());
    if (!match) return null;
    const seconds = (parseInt(match[1] ?? '0') * 60) + parseFloat(match[2]);
    return seconds > 0 ? seconds : null;
}
 
function renderRaceStats(results) {
    const winner = results.find(driver => driver.position === 1);
    const pole = currentRace?.qualifying?.find(driver => driver.position === 1);
 
    const fastest = getFastestLap(results);

    // Calculate biggest mover
    let biggestMover = null;
    let maxPositionsGained = 0;
 
    if (currentSession !== 'qualifying' && currentRace.qualifying) {
        results.forEach(driver => {
            const quali = currentRace.qualifying.find(q => q.driver_name === driver.driver_name);
            if (quali) {
                const gained = quali.position - driver.position;
                if (gained > maxPositionsGained) {
                    maxPositionsGained = gained;
                    biggestMover = driver;
                }
            }
        });
    }
 
    const cards = [
        statCard('Winner', winner?.driver_name ?? '--', { sub: winner?.team_name, index: 0 }),
        statCard('Pole Position', pole?.driver_name ?? '--', { sub: pole?.best_lap_time, index: 1 }),
        statCard('Fastest Lap', fastest?.driver_name ?? '--', { sub: fastest?.best_lap_time, index: 2 })
    ];
 
    if (biggestMover && maxPositionsGained > 0) {
        cards.push(statCard('Biggest Mover', biggestMover.driver_name, { sub: `+${maxPositionsGained} Positions`, accent: true, index: 3 }));
    } else {
        const finishers = results.filter(isFinished).length;
        const dnfs = results.length - finishers;
        cards.push(statCard('Finished', `${finishers}/${results.length}`, { sub: `${dnfs} DNF`, accent: dnfs === 0, index: 3 }));
    }
 
    document.getElementById('race-stats-cards').innerHTML = cards.join('');
}
 
