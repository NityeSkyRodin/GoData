const TRACK_PADDING = 30;
const builtTrackPaths = new Map();
 
function normalizeTrackName(name) {
    return String(name ?? '')
        .normalize('NFD').replace(/[\u0300-\u036f]/g, '')
        .toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim();
}
 
// Rotate the stored north-up path and fit it back into the 500x400 viewBox
function buildTrackPath(track) {
    if (builtTrackPaths.has(track)) return builtTrackPaths.get(track);
 
    const nums = track.path.match(/-?\d+(?:\.\d+)?/g).map(Number);
    const rad = (track.rotate || 0) * Math.PI / 180;
    const cos = Math.cos(rad), sin = Math.sin(rad);
    const points = [];
    for (let i = 0; i < nums.length; i += 2) {
        const x = nums[i] - 250, y = nums[i + 1] - 200;
        points.push([x * cos - y * sin, x * sin + y * cos]);
    }
 
    const xs = points.map(p => p[0]), ys = points.map(p => p[1]);
    const minX = Math.min(...xs), minY = Math.min(...ys);
    const width = Math.max(...xs) - minX, height = Math.max(...ys) - minY;
    const scale = Math.min((500 - 2 * TRACK_PADDING) / width, (400 - 2 * TRACK_PADDING) / height);
    const offsetX = (500 - width * scale) / 2, offsetY = (400 - height * scale) / 2;
 
    const d = 'M' + points
        .map(([x, y]) => `${(offsetX + (x - minX) * scale).toFixed(1)} ${(offsetY + (y - minY) * scale).toFixed(1)}`)
        .join(' L') + ' Z';
    builtTrackPaths.set(track, d);
    return d;
}
 
// Accepts circuit names like "Silverstone", "Circuit de Spa-Francorchamps", "Yas Marina Circuit"
function findTrack(trackName) {
    const needle = ` ${normalizeTrackName(trackName)} `;
    if (needle.trim() === '') return null;
    // Longest matching alias wins, so specific names beat generic ones
    let best = null;
    for (const track of Object.values(TRACK_SVGS)) {
        for (const alias of [normalizeTrackName(track.name), ...track.aliases]) {
            if (needle.includes(` ${alias} `) && (!best || alias.length > best.len)) {
                best = { track, len: alias.length };
            }
        }
    }
    return best?.track ?? null;
}
 
function getTrackSvgPath(trackName) {
    const track = findTrack(trackName);
    if (!track) {
        console.warn(`Geen track-SVG gevonden voor "${trackName}" — voeg een alias toe in TRACK_SVGS.`);
        return '';
    }
    return buildTrackPath(track);
}
 
